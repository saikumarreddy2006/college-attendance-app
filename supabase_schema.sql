-- ====================================================================
-- SUPABASE CLOUD POSTGRESQL SCHEMA WITH ROW LEVEL SECURITY (RLS)
-- ====================================================================
-- This schema configures PostgreSQL for Supabase Auth and multi-tenant
-- College Attendance Management with strict Row Level Security.
-- Every user can ONLY read, create, update, and delete their own data.
-- ====================================================================

-- 1. Profiles Table (linked to Supabase Auth users)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    avatar_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL
);

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view own profile"
    ON public.profiles FOR SELECT
    USING (auth.uid() = id);

CREATE POLICY "Users can update own profile"
    ON public.profiles FOR UPDATE
    USING (auth.uid() = id);

CREATE POLICY "Users can insert own profile"
    ON public.profiles FOR INSERT
    WITH CHECK (auth.uid() = id);

-- 2. Settings Table
CREATE TABLE IF NOT EXISTS public.settings (
